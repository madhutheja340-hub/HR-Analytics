######## CONBINING THE BOTH TABLES ######
CREATE TABLE HR_MASTER AS
SELECT
    H1.*,
    H2.*
FROM HR_1 AS H1
INNER JOIN HR_2 AS H2
ON H1.EmployeeNumber = H2.`EmployeeID`;

SELECT * FROM HR_MASTER;


# CALCULATING THE TOTAL EMPLOYEES COUNT.
