#### CREATING THE PROCEDURE TO CALCULATE THE ATTRITION COUNT BY USING "IN AND OUT" PROCEDURE.
DELIMITER //
CREATE PROCEDURE ATTRITION_COUNT(ATT TEXT, OUT ATT_COUNT INT)
BEGIN
     SELECT COUNT(EMPLOYEENUMBER) INTO ATT_COUNT FROM HR_MASTER
     WHERE ATTRITION=ATT;
END //
DELIMITER ;
CALL ATTRITION_COUNT("YES",@TOTAL);
SELECT @TOTAL;
 
 
